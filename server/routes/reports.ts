function getLAOffset(forDate?: Date): string {
  const d = forDate || new Date();
  const formatter = new Intl.DateTimeFormat("en-US", {
    timeZone: "America/Los_Angeles",
    timeZoneName: "shortOffset",
  });
  const parts = formatter.formatToParts(d);
  const tzPart = parts.find((p) => p.type === "timeZoneName");
  if (tzPart?.value) {
    const match = tzPart.value.match(/GMT([+-]?\d+)/);
    if (match) {
      const hours = parseInt(match[1], 10);
      const sign = hours <= 0 ? "-" : "+";
      return `${sign}${String(Math.abs(hours)).padStart(2, "0")}:00`;
    }
  }
  return "-08:00";
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function fetchTodaysCalendar(
  saKey: ServiceAccountKey,
  email: string,
  label: string,
): Promise<string> {
  try {
    const token = await getServiceToken(
      saKey,
      "https://www.googleapis.com/auth/calendar.readonly",
      email,
    );
    const now = new Date();
    const laDate = now.toLocaleDateString("en-CA", {
      timeZone: "America/Los_Angeles",
    });
    const offset = getLAOffset();
    const timeMin = `${laDate}T00:00:00${offset}`;
    const timeMax = `${laDate}T23:59:59${offset}`;
    const url = `https://www.googleapis.com/calendar/v3/calendars/${email}/events?timeMin=${encodeURIComponent(timeMin)}&timeMax=${encodeURIComponent(timeMax)}&singleEvents=true&orderBy=startTime&maxResults=25`;
    const r = await fetchT(url, {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!r.ok) return `(Failed to fetch ${label} calendar)`;
    const data = await r.json();
    if (!data.items?.length) return "No events today.";
    return data.items
      .map((e: any) => {
        const time = e.start?.dateTime
          ? new Date(e.start.dateTime).toLocaleTimeString("en-US", {
              hour: "numeric",
              minute: "2-digit",
              timeZone: "America/Los_Angeles",
            })
          : "All day";
        return `• ${time} — ${e.summary || "Busy"}`;
      })
      .join("\n");
  } catch (_) {
    return `(Calendar fetch error for ${label})`;
  }
}

async function fetchTomorrowsCalendar(
  saKey: ServiceAccountKey,
): Promise<string> {
  try {
    const token = await getServiceToken(
      saKey,
      "https://www.googleapis.com/auth/calendar.readonly",
      TONY_EMAIL,
    );
    const now = new Date();
    const tomorrow = new Date(now.getTime() + 24 * 60 * 60 * 1000);
    const laDate = tomorrow.toLocaleDateString("en-CA", {
      timeZone: "America/Los_Angeles",
    });
    const offset = getLAOffset(tomorrow);
    const timeMin = `${laDate}T00:00:00${offset}`;
    const timeMax = `${laDate}T23:59:59${offset}`;
    const url = `https://www.googleapis.com/calendar/v3/calendars/${TONY_EMAIL}/events?timeMin=${encodeURIComponent(timeMin)}&timeMax=${encodeURIComponent(timeMax)}&singleEvents=true&orderBy=startTime&maxResults=25`;
    const r = await fetchT(url, {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!r.ok) return "(Failed to fetch)";
    const data = await r.json();
    if (!data.items?.length) return "No events tomorrow.";
    return data.items
      .map((e: any) => {
        const time = e.start?.dateTime
          ? new Date(e.start.dateTime).toLocaleTimeString("en-US", {
              hour: "numeric",
              minute: "2-digit",
              timeZone: "America/Los_Angeles",
            })
          : "All day";
        return `• ${time} — ${e.summary || "Busy"}`;
      })
      .join("\n");
  } catch (_) {
    return "(Calendar error)";
  }
}

