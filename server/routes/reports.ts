function formatDate(): string {
  const d = new Date();
  return d.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

async function createFormattedGoogleDoc(
  projectName: string,
  reportBody: string,
  teamMembers: string,
  token: string,
): Promise<{ docId: string; docUrl: string }> {
  const createRes = await fetch("https://docs.googleapis.com/v1/documents", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${token}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      title: `${projectName} — Assembled Report`,
    }),
  });
  if (!createRes.ok)
    throw new Error(`Doc create failed: ${await createRes.text()}`);
  const doc = await createRes.json();
  const docId = doc.documentId;
  const docUrl = `https://docs.google.com/document/d/${docId}`;

  const dateStr = formatDate();
  const headerBlock = [
    "CLUB 34",
    "",
    projectName,
    "",
    dateStr,
    `Prepared by: ${teamMembers}`,
    "",
    "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━",
    "",
  ].join("\n");

  const footerBlock = [
    "",
    "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━",
    "",
    "Generated by Janus | Club 34",
    "This report was automatically assembled from project artifacts.",
  ].join("\n");

  const fullText = headerBlock + reportBody + footerBlock;

  const insertRequests: any[] = [
    { insertText: { location: { index: 1 }, text: fullText } },
  ];

  await fetch(
    `https://docs.googleapis.com/v1/documents/${docId}:batchUpdate`,
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ requests: insertRequests }),
    },
  );

  const formatRequests: any[] = [];
  const base = 1;

  const club34End = base + "CLUB 34".length;
  formatRequests.push({
    updateTextStyle: {
      range: { startIndex: base, endIndex: club34End },
      textStyle: {
        bold: true,
        fontSize: { magnitude: 10, unit: "PT" },
        foregroundColor: { color: { rgbColor: BRAND_GRAY } },
        smallCaps: true,
      },
      fields: "bold,fontSize,foregroundColor,smallCaps",
    },
  });

  const titleStart = base + headerBlock.indexOf(projectName);
  const titleEnd = titleStart + projectName.length;
  formatRequests.push(
    {
      updateParagraphStyle: {
        range: { startIndex: titleStart, endIndex: titleEnd + 1 },
        paragraphStyle: { namedStyleType: "HEADING_1" },
        fields: "namedStyleType",
      },
    },
    {
      updateTextStyle: {
        range: { startIndex: titleStart, endIndex: titleEnd },
        textStyle: {
          bold: true,
          fontSize: { magnitude: 24, unit: "PT" },
          foregroundColor: { color: { rgbColor: BRAND_DARK } },
        },
        fields: "bold,fontSize,foregroundColor",
      },
    },
  );

  const bodyStart = base + headerBlock.length;
  const bodyEnd = base + headerBlock.length + reportBody.length;
  formatRequests.push({
    updateTextStyle: {
      range: { startIndex: bodyStart, endIndex: bodyEnd },
      textStyle: {
        fontSize: { magnitude: 11, unit: "PT" },
        foregroundColor: { color: { rgbColor: BRAND_DARK } },
      },
      fields: "fontSize,foregroundColor",
    },
  });

  for (const marker of SECTION_MARKERS) {
    const markerIdx = fullText.indexOf(marker);
    if (markerIdx === -1) continue;
    const mStart = base + markerIdx;
    const mEnd = mStart + marker.length;
    formatRequests.push(
      {
        updateParagraphStyle: {
          range: { startIndex: mStart, endIndex: mEnd + 1 },
          paragraphStyle: { namedStyleType: "HEADING_2" },
          fields: "namedStyleType",
        },
      },
      {
        updateTextStyle: {
          range: { startIndex: mStart, endIndex: mEnd },
          textStyle: {
            bold: true,
            fontSize: { magnitude: 14, unit: "PT" },
            foregroundColor: { color: { rgbColor: BRAND_DARK } },
          },
          fields: "bold,fontSize,foregroundColor",
        },
      },
    );
  }

  if (formatRequests.length > 0) {
    await fetch(
      `https://docs.googleapis.com/v1/documents/${docId}:batchUpdate`,
      {
        method: "POST",
        headers: {
          Authorization: `Bearer ${token}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({ requests: formatRequests }),
      },
    );
  }

  return { docId, docUrl };
}

