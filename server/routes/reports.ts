function getThisWeekMondayLA(): string {
  const now = new Date();
  const laDate = new Date(
    now.toLocaleString("en-US", { timeZone: "America/Los_Angeles" }),
  );
  const day = laDate.getDay();
  const diffToMonday = day === 0 ? -6 : 1 - day;
  laDate.setDate(laDate.getDate() + diffToMonday);
  return laDate.toLocaleDateString("en-CA", {
    timeZone: "America/Los_Angeles",
  });
}

function getNextWeekRange(): { monday: string; friday: string } {
  const now = new Date();
  const laDate = new Date(
    now.toLocaleString("en-US", { timeZone: "America/Los_Angeles" }),
  );
  const day = laDate.getDay();
  const daysToNextMonday = day === 0 ? 1 : 8 - day;
  const nextMon = new Date(laDate);
  nextMon.setDate(laDate.getDate() + daysToNextMonday);
  const nextFri = new Date(nextMon);
  nextFri.setDate(nextMon.getDate() + 4);
  return {
    monday: nextMon.toLocaleDateString("en-CA"),
    friday: nextFri.toLocaleDateString("en-CA"),
  };
}

