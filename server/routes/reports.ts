function weatherCodeToEmoji(code: number): string {
  const desc = weatherCodeToDescription(code);
  const match = desc.match(/[\u{1F300}-\u{1F9FF}]|[\u{2600}-\u{26FF}]|[\u{2700}-\u{27BF}]/u);
  return match ? match[0] : "🌡️";
}

/** Google Weather API condition type → human-readable description (parallel to weatherCodeToDescription). */
function googleConditionToDescription(type: string): string {
  return googleCondToDescription(type);
}

/** Google Weather API condition type → single emoji (parallel to weatherCodeToEmoji). */
function googleConditionToEmoji(type: string): string {
  return googleCondToEmoji(type);
}

function formatCalendarForAI(events: any[]): CalEvent[] {
  if (!events.length) return [];
  return events.map(e => {
    if (e.allDay) return { time: "All day", event: e.summary, allDay: true };
    const st = new Date(e.start).toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit", timeZone: "America/Los_Angeles" });
    return { time: st, event: e.summary };
  });
}

async function generateEmailData(
  childName: string,
  weatherSummary: string,
  weatherRaw: WeatherSourceData | null,
  news: { us: NewsItem[]; world: NewsItem[] },
  financial: MarketSnapshot,
  childEvents: any[],
  dadEvents: any[],
  momEvents: any[],
): Promise<EmailData> {
  const today = new Date().toLocaleDateString("en-US", {
    weekday: "long", month: "long", day: "numeric", year: "numeric", timeZone: "America/Los_Angeles",
  });

  const childCal = formatCalendarForAI(childEvents);
  const dadCal = formatCalendarForAI(dadEvents);
  const momCal = formatCalendarForAI(momEvents);
  const rawWeather = weatherRaw
    ? extractWeatherData(weatherRaw)
    : { current: null, slots: [] };
  const slotLabels = new Map([
    [8, "Morning"],
    [12, "Midday"],
    [15, "Afternoon"],
    [19, "Evening"],
  ]);
  const exactWeather = {
    condition: rawWeather.current
      ? weatherCodeToDescription(rawWeather.current.code).replace(
          /\s*[\u{1F300}-\u{1F9FF}\u{2600}-\u{27BF}]+\s*$/u,
          "",
        )
      : "Unavailable",
    icon: rawWeather.current ? weatherCodeToEmoji(rawWeather.current.code) : "🌡️",
    tempNow: rawWeather.current?.temp ?? null,
    feelsLike: rawWeather.current?.feels ?? null,
    slots: rawWeather.slots.map((slot) => ({
      label: slotLabels.get(slot.hour) ?? `${slot.hour}:00`,
      icon: weatherCodeToEmoji(slot.code),
      temp: slot.temp,
    })),
    wardrobeTip: (() => {
      const temperatures = [
        rawWeather.current?.temp,
        ...rawWeather.slots.map((slot) => slot.temp),
      ].filter((temp): temp is number => typeof temp === "number");
      const rainChance = Math.max(0, ...rawWeather.slots.map((slot) => slot.precip));
      if (temperatures.length === 0) return "Weather data unavailable";
      const low = Math.min(...temperatures);
      const high = Math.max(...temperatures);
      if (rainChance >= 40) return "Bring an umbrella or rain layer";
      if (high >= 85) return "It will be hot this afternoon — wear light clothing and bring water";
      if (low <= 60 && high >= 75) return "Start with a light layer you can remove as it warms up";
      if (low <= 60) return "A light jacket or sweater will help this morning";
      return "Comfortable, light layers should work well today";
    })(),
    rainAlert: (() => {
      const wettest = [...rawWeather.slots].sort(
        (left, right) => right.precip - left.precip,
      )[0];
      if (!wettest || wettest.precip < 40) return null;
      const label = slotLabels.get(wettest.hour) ?? `${wettest.hour}:00`;
      return `${Math.round(wettest.precip)}% chance of rain around ${label.toLowerCase()}`;
    })(),
    asOf: weatherRaw?.current?.observedAt
      ? new Date(weatherRaw.current.observedAt).toLocaleTimeString("en-US", {
          timeZone: "America/Los_Angeles",
          hour: "numeric",
          minute: "2-digit",
          timeZoneName: "short",
        })
      : null,
    source: weatherRaw?.source ?? null,
  };

  const prompt = `You are Janus. Today is ${today}. Generate a morning briefing JSON for ${childName} (teenage girl).

Return ONLY valid JSON matching this exact schema (no markdown, no extra fields):
{
  "subject": "☀️ Good Morning, ${childName}! · ${today}",
  "weather": {
    "condition": "brief description e.g. Sunny",
    "icon": "single weather emoji",
    "tempNow": ${rawWeather.current?.temp ?? "null"},
    "feelsLike": ${rawWeather.current?.feels ?? "null"},
    "slots": [
      {"label":"Morning","icon":"emoji","temp":number},
      {"label":"Midday","icon":"emoji","temp":number},
      {"label":"Afternoon","icon":"emoji","temp":number},
      {"label":"Evening","icon":"emoji","temp":number}
    ],
    "wardrobeTip": "1 short practical tip for what to wear/bring",
    "rainAlert": null or "Rain likely at 2pm — bring umbrella"
  },
  "markets": {
    "indices": [{"name":"string","value":"string","change":"string","up":boolean}],
    "commodities": [{"name":"string","value":"string","change":"string","up":boolean}],
    "currencies": [{"name":"string","value":"string","change":"string","up":boolean}]
  },
  "childSchedule": [{"time":"9:00 AM","event":"string","allDay":false}],
  "dadSchedule": [{"time":"string","event":"string"}],
  "momSchedule": [{"time":"string","event":"string"}]
}

Data inputs:
WEATHER (full day 6am–11pm): ${weatherSummary.split('\n').slice(0, 20).join('\n')}
FINANCIAL (use this data, don't make up different numbers): ${JSON.stringify(financial)}
${childName.toUpperCase()}'S CALENDAR: ${JSON.stringify(childCal)}
DAD'S CALENDAR: ${JSON.stringify(dadCal)}
MOM'S CALENDAR: ${JSON.stringify(momCal)}

CRITICAL: Use the EXACT financial values from the input. Do not fabricate data. For weather slots, use the actual hourly data above to pick realistic temps and emojis for Morning (8am), Midday (12pm), Afternoon (3pm), Evening (7pm).`;

  const sanitizeString = (s: any, fallback: string, maxLen = 200): string => {
    if (typeof s !== "string") return fallback;
    return s.replace(/<[^>]*>/g, "").trim().slice(0, maxLen) || fallback;
  };

  const sanitizeEmailData = (parsed: any): EmailData => {
    return {
      subject: sanitizeString(parsed?.subject, `☀️ Good Morning, ${childName}! · ${today}`, 150),
      weather: exactWeather,
      markets: financial,
      news,
      childSchedule: Array.isArray(parsed?.childSchedule) ? parsed.childSchedule : childCal,
      dadSchedule: Array.isArray(parsed?.dadSchedule) ? parsed.dadSchedule : dadCal,
      momSchedule: Array.isArray(parsed?.momSchedule) ? parsed.momSchedule : momCal,
    };
  };

  try {
    const parsed = await callAIJSON(prompt, 4000);
    return sanitizeEmailData(parsed);
  } catch {
    return {
      subject: `☀️ Good Morning, ${childName}! · ${today}`,
      weather: exactWeather,
      markets: financial,
      news,
      childSchedule: childCal,
      dadSchedule: dadCal,
      momSchedule: momCal,
    };
  }
}

