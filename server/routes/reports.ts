type Status = "ok" | "degraded" | "error";
interface CheckResult {
  name: string;
  label: string;
  category: string;
  status: Status;
  latency_ms: number;
  message: string | null;
}

async function runCheck(
  name: string,
  label: string,
  category: string,
  fn: () => Promise<string | null>,
): Promise<CheckResult> {
  const start = Date.now();
  try {
    const error = await fn();
    return {
      name,
      label,
      category,
      status: error ? "error" : "ok",
      latency_ms: Date.now() - start,
      message: error,
    };
  } catch (e) {
    return {
      name,
      label,
      category,
      status: "error",
      latency_ms: Date.now() - start,
      message: e instanceof Error ? e.message : "Unknown error",
    };
  }
}

function statusIcon(s: Status): string {
  if (s === "ok") return "✅";
  if (s === "degraded") return "⚠️";
  return "❌";
}

function statusColor(s: Status): string {
  if (s === "ok") return "#4ade80";
  if (s === "degraded") return "#fb923c";
  return "#f87171";
}

function statusBg(s: Status): string {
  if (s === "ok") return "#0a2015";
  if (s === "degraded") return "#2a1a06";
  return "#2a0a0a";
}

